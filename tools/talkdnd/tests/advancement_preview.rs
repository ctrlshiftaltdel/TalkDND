//! Synthetic legacy saves exercising the real read-only CLI.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

use combat_sim::content::schema::{ContentFile, DomainEntity};
use combat_sim::content::{ContentPack, Distribution, PackMeta};
use serde_json::{json, Value};

struct Fixture {
    root: PathBuf,
    save: PathBuf,
}

impl Fixture {
    fn new(schema: u32, ruleset: &str) -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let root = loop {
            let path = std::env::temp_dir().join(format!(
                "talkdnd-growth-preview-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            match fs::create_dir(&path) {
                Ok(()) => break path,
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(error) => panic!("could not create preview fixture: {error}"),
            }
        };
        let save = root.join("Saves/2030-01-02-01");
        let fixture = Self { root, save };
        write(&fixture.root, "AGENTS.md", b"synthetic play root");
        write(
            &fixture.save,
            "save-meta.yaml",
            format!("schema: {schema}\n").as_bytes(),
        );
        write(
            &fixture.save,
            "combat/campaign.yaml",
            format!("name: Fixture\nruleset: \"{ruleset}\"\nstate_dir: .\nparty: [hero]\n")
                .as_bytes(),
        );
        fixture.card(3, "");
        write(&fixture.save, "Sessions/2030-01-02.md", b"synthetic log\n");
        fixture
    }

    fn card(&self, level: i32, after: &str) {
        write(
            &self.save,
            "Characters/hero.md",
            format!(
                "# Synthetic Hero\n\n```combat yaml\nid: hero\nname: Synthetic Hero\nlevel: {level}\nabilities: {{str: 17, dex: 20, con: 12}}\nnotes: fighter 3. Generated by talkdnd from SRD/local data\n```\n{after}"
            )
            .as_bytes(),
        );
    }

    fn pack(&self, edition: &str, dist: Distribution, id: &str, feat: DomainEntity) {
        let pack = ContentPack::new(
            PackMeta {
                id: id.into(),
                name: None,
                edition: edition.into(),
                source: Some("synthetic".into()),
                license: Some("test".into()),
                distribution: dist,
                schema_version: combat_sim::content::pack::SCHEMA_VERSION,
                content_hash: None,
                created_at: None,
                description: None,
            },
            ContentFile {
                feats: Some(vec![feat]),
                ..Default::default()
            },
        )
        .unwrap();
        let path = if dist == Distribution::Full {
            format!("Rules/packs/{id}.pack.json")
        } else {
            format!("Rules/combat/{edition}/srd/{id}.pack.json")
        };
        write(&self.root, &path, &serde_json::to_vec(&pack).unwrap());
    }

    fn unlock_book(&self, edition: &str) {
        write(
            &self.root,
            ".talkdnd/books.yaml",
            format!(
                "books:\n- edition: \"{edition}\"\n  book: phb\n  status: identified\n  source: Rules/{edition}/synthetic/index\n  method: content\n  evidence: synthetic\n  stamp: fixture\n"
            )
            .as_bytes(),
        );
    }

    fn command(&self, args: &[&str]) -> Output {
        let before = snapshot(&self.root);
        let output = Command::new(env!("CARGO_BIN_EXE_talkdnd"))
            .arg("--root")
            .arg(&self.root)
            .args(args)
            .output()
            .unwrap();
        assert_eq!(before, snapshot(&self.root), "the CLI changed the fixture");
        output
    }

    fn preview(&self) -> Value {
        let output = self.command(&[
            "advancement",
            "identity-preview",
            "--level-up",
            "hero",
            "--json",
        ]);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let preview: Value = serde_json::from_slice(&output.stdout).unwrap();
        assert_eq!(preview["consistency"], "unverified");
        assert_eq!(preview["write_capability"], "unverified");
        assert!(preview.get("preview_id").is_none());
        preview
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        // The fixture creates this directory atomically and owns it.
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn write(root: &Path, relative: &str, data: &[u8]) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, data).unwrap();
}

fn snapshot(root: &Path) -> BTreeMap<PathBuf, Option<Vec<u8>>> {
    fn visit(root: &Path, path: &Path, tree: &mut BTreeMap<PathBuf, Option<Vec<u8>>>) {
        for entry in fs::read_dir(path).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            let directory = entry.file_type().unwrap().is_dir();
            let contents = (!directory).then(|| fs::read(&path).unwrap());
            tree.insert(path.strip_prefix(root).unwrap().to_path_buf(), contents);
            if directory {
                visit(root, &path, tree);
            }
        }
    }
    let mut tree = BTreeMap::new();
    visit(root, root, &mut tree);
    tree
}

fn feat(id: &str, category: &str, minimum: u32) -> DomainEntity {
    DomainEntity {
        id: id.into(),
        name: Some(format!("Fixture {id}")),
        text: Some("never print synthetic rule body".into()),
        manual: Some("never print synthetic hidden effect".into()),
        data: Some(json!({
            "type": category,
            "prerequisites": { "minimum_level": minimum },
        })),
        ..Default::default()
    }
}

#[test]
fn both_legacy_schemas_preview_without_lock_cache_or_log_writes() {
    for schema in [9, 10] {
        let fixture = Fixture::new(schema, "5e-srd");
        #[cfg(unix)]
        let original_permissions = {
            use std::os::unix::fs::PermissionsExt;

            let original = fs::metadata(&fixture.save).unwrap().permissions();
            fs::set_permissions(&fixture.save, fs::Permissions::from_mode(0o555)).unwrap();
            original
        };
        let preview = fixture.preview();
        #[cfg(unix)]
        fs::set_permissions(&fixture.save, original_permissions).unwrap();
        assert_eq!(preview["target_level"], 4);
        assert_eq!(preview["identity"], "review_required");
        assert_eq!(preview["abilities"][0]["modifier_after_plus_one"], 4);
        assert!(preview["abilities"][1]["modifier_after_plus_one"].is_null());
        assert_eq!(preview["encounter"], "clear_at_read");
        let display = fixture.command(&["advancement", "identity-preview", "--level-up", "hero"]);
        assert!(display.status.success());
        assert!(String::from_utf8_lossy(&display.stdout).contains("consistency: unverified"));

        // The existing identity-only entry keeps its shape and behavior.
        let old = fixture.command(&["advancement", "identity-preview", "--json"]);
        assert!(old.status.success());
        let old: Value = serde_json::from_slice(&old.stdout).unwrap();
        assert_eq!(old["cards"][0]["status"], "review_required");
        assert!(old.get("target_level").is_none());
    }
}

#[test]
fn four_rulesets_use_only_their_catalog_and_full_unlock() {
    for (ruleset, edition, srd_id, full) in [
        ("5e-srd", "2014", "srd-5.1-feats", false),
        ("5.5e-srd", "2024", "srd-5.2.1-feats", false),
        ("5e-full", "2014", "srd-5.1-feats", true),
        ("5.5e-full", "2024", "srd-5.2.1-feats", true),
    ] {
        let fixture = Fixture::new(10, ruleset);
        let srd_feat = format!("srd-{edition}");
        let full_feat = format!("full-{edition}");
        let other = if edition == "2014" { "2024" } else { "2014" };
        fixture.pack(
            edition,
            Distribution::Srd,
            srd_id,
            feat(&srd_feat, "general", 4),
        );
        fixture.pack(
            edition,
            Distribution::Full,
            &format!("full-{edition}-phb"),
            feat(&full_feat, "epic-boon", 19),
        );
        fixture.pack(
            other,
            Distribution::Full,
            &format!("full-{other}-phb"),
            feat("wrong-edition-only", "general", 4),
        );
        fixture.unlock_book(edition);
        let preview = fixture.preview();
        assert_eq!(preview["ruleset"], ruleset);
        let opportunity = if edition == "2014" {
            "ability_score_improvement_or_optional_feat"
        } else {
            "ability_score_improvement_feat_or_other_qualified_feat"
        };
        assert_eq!(preview["opportunity"], opportunity);
        let choices = preview["candidates"].as_array().unwrap();
        assert_eq!(choices.len(), if full { 2 } else { 1 });
        let srd = choices.iter().find(|row| row["id"] == srd_feat).unwrap();
        assert_eq!(srd["source"], srd_id);
        assert_eq!(srd["eligibility"], "unknown");
        if full {
            let full = choices.iter().find(|row| row["id"] == full_feat).unwrap();
            assert_eq!(full["category"], "epic-boon");
            assert_eq!(full["eligibility"], "not_met");

            fixture.pack(
                edition,
                Distribution::Full,
                &format!("full-{edition}-phb"),
                feat("updated-full-source", "general", 4),
            );
            let updated = fixture.preview();
            assert!(updated.to_string().contains("updated-full-source"));
            assert!(!updated.to_string().contains(&full_feat));
        }
        assert!(!preview.to_string().contains("never print synthetic"));
    }
}

#[test]
fn invalid_qualifying_sources_and_dm_characters_are_not_previewed() {
    let fixture = Fixture::new(10, "5.5e-full");
    fixture.pack(
        "2024",
        Distribution::Full,
        "full-2024-phb",
        feat("locked", "general", 4),
    );
    let args = ["advancement", "identity-preview", "--level-up", "hero"];
    let locked = fixture.command(&args);
    assert!(!locked.status.success());
    assert!(String::from_utf8_lossy(&locked.stderr).contains("缺少同版已授权"));
    fixture.unlock_book("2014");
    let wrong = fixture.command(&args);
    assert!(!wrong.status.success());
    assert!(String::from_utf8_lossy(&wrong.stderr).contains("缺少同版已授权"));

    fixture.unlock_book("2024");
    let sheet = |controller: &str, ruleset: &str| {
        format!(
            "version: 1\nid: hero\nname: Synthetic Hero\nfile: Characters/hero.md\nruleset: \"{ruleset}\"\ncontroller: {controller}\ninfo: {{class: fighter}}\ncombat: {{level: 3}}\n"
        )
    };
    write(
        &fixture.save,
        "sheets/hero.yaml",
        sheet("player", "5e-srd").as_bytes(),
    );
    let wrong = fixture.command(&args);
    assert!(!wrong.status.success());
    assert!(String::from_utf8_lossy(&wrong.stderr).contains("规则版次不一致"));
    write(
        &fixture.save,
        "sheets/hero.yaml",
        sheet("dm", "5.5e-full").as_bytes(),
    );
    let hidden = fixture.command(&args);
    assert!(!hidden.status.success());
    assert!(String::from_utf8_lossy(&hidden.stderr).contains("未找到该玩家角色"));
    assert!(!String::from_utf8_lossy(&hidden.stderr).contains("Synthetic Hero"));
}

#[test]
fn structured_and_markdown_conflicts_omit_only_unreliable_ability_predictions() {
    let fixture = Fixture::new(9, "5e-srd");
    write(
        &fixture.save,
        "sheets/hero.yaml",
        b"version: 1\nid: hero\nname: Synthetic Hero\nfile: Characters/hero.md\nruleset: \"2014\"\ncontroller: player\ninfo: {class: fighter}\ncombat: {level: 3, abilities: {str: 16, dex: 20, con: 12}}\n",
    );
    let preview = fixture.preview();
    assert_eq!(preview["class_source"], "structured_sheet");
    assert_eq!(
        preview["abilities_with_conflicting_sources"],
        json!(["str"])
    );
    assert!(preview["unknowns"]
        .as_array()
        .unwrap()
        .contains(&json!("conflicting_ability_sources")));
    let abilities = preview["abilities"].as_array().unwrap();
    assert!(!abilities.iter().any(|row| row["ability"] == "str"));
    assert!(abilities
        .iter()
        .any(|row| row["ability"] == "con" && row["current_score"] == 12));
}

#[test]
fn open_and_uncertain_encounters_allow_only_an_unbound_preview() {
    let fixture = Fixture::new(10, "5.5e-srd");
    let marker = "11111111111111111111111111111111";
    fixture.card(18, &format!("<!-- talkdnd-identity: {marker} -->\n"));
    let matching =
        format!("version: 1\ncard: Characters/hero.md\ntoken: \"{marker}\"\nhistory: unknown\n");
    write(&fixture.save, "advancement/hero.yaml", matching.as_bytes());
    let state = json!({
        "schema_version": 5,
        "party_state": fixture.save.join("combat/party-state.yaml"),
        "registration": { "id": "0123456789abcdef0123456789abcdef" },
        "log": ["synthetic DM-only encounter detail"],
    });
    write(
        &fixture.save,
        "combat/fight.state.json",
        &serde_json::to_vec(&state).unwrap(),
    );
    assert!(
        combat_sim::encounter_lifecycle::require_between_encounters(&fixture.save)
            .unwrap_err()
            .to_string()
            .contains("still open")
    );
    let active = fixture.preview();
    assert_eq!(active["identity"], "matched");
    assert_eq!(active["opportunity"], "epic_boon_or_other_qualified_feat");
    assert_eq!(active["encounter"], "active_or_unknown");
    assert!(!active.to_string().contains("DM-only encounter detail"));

    write(&fixture.save, "combat/fight.state.json", b"broken JSON");
    write(
        &fixture.save,
        "advancement/hero.yaml",
        matching
            .replace(marker, "22222222222222222222222222222222")
            .as_bytes(),
    );
    let uncertain = fixture.preview();
    assert_eq!(uncertain["encounter"], "active_or_unknown");
    assert_eq!(uncertain["identity"], "binding_mismatch");
    assert!(!uncertain.to_string().contains(marker));
    assert!(uncertain.get("before_digest").is_none());
}
