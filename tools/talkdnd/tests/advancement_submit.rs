#[test]
fn encounter_states_only_allow_preview_until_the_dm_closes_them() {
    let _serial = serial();
    let fixture = Fixture::new("encounters");
    if !fixture.try_migrate_to_schema_11() {
        return;
    }

    let binding = fixture.derive_binding(&[]);
    let closed = |reason: &str| registration("abababababababababababababababab", Some(reason));

    // An open encounter only allows preview.
    encounter_state(
        &fixture,
        "fight.state.json",
        open_state(&fixture, "abababababababababababababababab"),
    );
    let before = fixture.snapshot_tree();
    let refused = fixture.submit(&binding);
    assert!(!refused.status.success(), "{}", stdout(&refused));
    assert!(
        stderr(&refused).contains("只允许预览"),
        "{}",
        stderr(&refused)
    );
    assert_eq!(fixture.snapshot_tree(), before);

    // A pending reaction is the same refusal.
    encounter_state(
        &fixture,
        "fight.state.json",
        pending_reaction_state(&fixture, "abababababababababababababababab"),
    );
    let before = fixture.snapshot_tree();
    let refused = fixture.submit(&binding);
    assert!(!refused.status.success());
    assert!(stderr(&refused).contains("只允许预览"));
    assert_eq!(fixture.snapshot_tree(), before);

    // A corrupt state cannot prove ownership: refuse.
    fs::write(fixture.save.join("combat/fight.state.json"), b"not json").unwrap();
    let before = fixture.snapshot_tree();
    let refused = fixture.submit(&binding);
    assert!(!refused.status.success());
    assert_eq!(fixture.snapshot_tree(), before);

    // Duplicate registration ids cannot prove ownership either.
    let state = open_state(&fixture, "abababababababababababababababab");
    encounter_state(&fixture, "fight.state.json", state.clone());
    encounter_state(&fixture, "boss.state.json", state);
    let before = fixture.snapshot_tree();
    let refused = fixture.submit(&binding);
    assert!(!refused.status.success());
    assert!(stderr(&refused).contains("只允许预览"));
    assert_eq!(fixture.snapshot_tree(), before);
    fs::remove_file(fixture.save.join("combat/boss.state.json")).unwrap();

    // A legacy pre-registration snapshot stays preview-only until the DM
    // registers and closes it.
    let legacy = json!({
        "schema_version": 1,
        "party_state": fixture.save.join("combat/party-state.yaml"),
    });
    encounter_state(&fixture, "fight.state.json", legacy);
    let before = fixture.snapshot_tree();
    let refused = fixture.submit(&binding);
    assert!(!refused.status.success());
    assert!(stderr(&refused).contains("只允许预览"));
    assert_eq!(fixture.snapshot_tree(), before);
    // The DM registers the old encounter and closes it with a review note.
    encounter_state(
        &fixture,
        "fight.state.json",
        json!({
            "schema_version": 5,
            "party_state": fixture.save.join("combat/party-state.yaml"),
            "registration": closed("Reviewed old encounter"),
        }),
    );

    // A normal explicit closure and a DM-retreat closure both allow submit.
    encounter_state(
        &fixture,
        "fight.state.json",
        json!({
            "schema_version": 5,
            "party_state": fixture.save.join("combat/party-state.yaml"),
            "registration": closed("Fixture retreat"),
        }),
    );
    let fresh_binding = fixture.derive_binding(&[]);
    let done = fixture.submit(&fresh_binding);
    assert!(done.status.success(), "{}", stdout(&done) + &stderr(&done));
}

/// The concurrency proof: the encounter gate is re-evaluated with the SAVE
/// lock held after the candidate is built, so an encounter reopened between
/// admit and publish stops the commit with no target written.
#[cfg(target_os = "linux")]
#[test]
fn a_concurrent_reopen_is_caught_by_the_in_lock_gate() {
    let _serial = serial();
    let fixture = Fixture::new("reopen");
    if !fixture.try_migrate_to_schema_11() || !admitted_ext4(&fixture) {
        return;
    }
    let closed = encounter_state(
        &fixture,
        "fight.state.json",
        json!({
            "schema_version": 5,
            "party_state": fixture.save.join("combat/party-state.yaml"),
            "registration": registration("abababababababababababababababab", Some("closed")),
        }),
    );

    let mut before_targets = snapshot_targets(&fixture);
    before_targets.remove(&PathBuf::from("combat/fight.state.json"));
    let slot = "2030-01-02-01";
    let backups_root = fixture.root.join("Saves").join("_backups");
    let evidence_root = backups_root.join(".operations");
    let evidence_dir = evidence_root.join(slot);
    fs::create_dir_all(&evidence_dir).unwrap();
    let operation_id = "adv-reopen-probe";
    let request = Request {
        root: &fixture.root,
        save_dir: &fixture.save,
        operation_id,
        evidence_root: &evidence_root,
        evidence_dir: &evidence_dir,
        backup_parent: &backups_root,
        candidate_parent: &backups_root,
        overlays: BTreeMap::new(),
        fault: None,
        extra_targets: vec![
            "advancement/hero.yaml".to_owned(),
            "save-meta.yaml".to_owned(),
        ],
        preview_id: Some(fixture.d_binding()),
        instance_tag: "",
        // The "concurrent" writer reopens the encounter right before the
        // publish stage, inside the SAVE-held section.
        hooks: talkdnd::advancement_commit::PublishHooks {
            before_any_publish: Some(&|_| {
                let open = open_state(&fixture, "abababababababababababababababab");
                fs::write(&closed, serde_json::to_vec(&open).unwrap()).unwrap();
            }),
            after_intent: None,
            after_recheck_before_publish: None,
        },
        inner_lock: InnerLockOptions::default(),
        ext4_metadata: true,
    };
    let failed = run_to_complete(&request).expect_err("the reopen must stop the commit");
    assert!(
        failed.report.published_paths.is_empty(),
        "{:?}",
        failed.report
    );
    assert!(
        failed
            .report
            .error
            .as_deref()
            .unwrap_or_default()
            .contains("只允许预览"),
        "{}",
        failed.report.error.clone().unwrap_or_default()
    );
    // The refusal happened before any target write: all protected targets
    // are byte-identical. The injected "concurrent" writer rewrote the
    // encounter state by design, so that one file is excluded from the
    // comparison; the D control state is already excluded by
    // `snapshot_targets`. A zero-write stop records `failed`, which allows
    // ordinary writes again.
    let mut after = snapshot_targets(&fixture);
    after.remove(&PathBuf::from("combat/fight.state.json"));
    assert_eq!(after, before_targets, "no target may change");
    assert_eq!(failed.report.protocol_state, adv::State::Failed);
    let lock = adv::open(&fixture.root, &fixture.save, &adv::OpenOptions::new()).unwrap();
    lock.check_ordinary_write()
        .expect("a zero-write stop records failed and allows ordinary writes");
}

