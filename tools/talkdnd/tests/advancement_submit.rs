#[cfg(target_os = "linux")]
#[test]
fn recovery_inspects_first_then_rolls_back_by_explicit_choice() {
    let _serial = serial();
    let fixture = leftover_in_doubt_fixture("recover-rollback", "adv-leftover-1");
    let leftover = fixture.snapshot_tree();

    // Inspect first: the CLI reports the stage and materials, writes
    // nothing, and does not auto-replay. An in_doubt leftover inspects with
    // exit 1 (attention required) — the contract under test is that it
    // writes nothing and reports the materials.
    let inspect = fixture.command(&["advancement", "recover"]);
    let out = stdout(&inspect);
    assert!(out.contains("只读检查"), "{out}");
    assert!(out.contains("未写任何目标"), "{out}");
    assert_eq!(fixture.snapshot_tree(), leftover, "inspect must not write");

    // Explicit rollback: targets return to the preimage, the protocol ends
    // `failed`, and ordinary writes are allowed again.
    let recover = fixture.command(&[
        "advancement",
        "recover",
        "--choice",
        "rollback",
        "--confirm",
    ]);
    assert!(
        recover.status.success(),
        "{}",
        stdout(&recover) + &stderr(&recover)
    );
    let out = stdout(&recover);
    assert!(out.contains("回滚到前像"), "{out}");
    assert!(
        out.contains("本次写入") || out.contains("此前已应用"),
        "{out}"
    );
    let lock = adv::open(&fixture.root, &fixture.save, &adv::OpenOptions::new()).unwrap();
    lock.check_ordinary_write()
        .expect("a finished rollback allows ordinary writes again");

    // A repeated recovery is refused at the terminal write (the leftover is
    // already resolved) and re-applies nothing: every file is already at
    // its rolled-back state and no byte changes.
    let after = fixture.snapshot_tree();
    let repeat = fixture.command(&[
        "advancement",
        "recover",
        "--choice",
        "rollback",
        "--confirm",
    ]);
    assert!(
        !repeat.status.success(),
        "{}",
        stdout(&repeat) + &stderr(&repeat)
    );
    let out = stdout(&repeat) + &stderr(&repeat);
    assert!(out.contains("终态"), "{out}");
    assert_eq!(
        fixture.snapshot_tree(),
        after,
        "repeat recovery must not write"
    );
}

