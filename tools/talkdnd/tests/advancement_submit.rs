//! ADV-P1-10: the explicit advancement submit and recovery entries, end to
//! end on synthetic fixtures through the real CLI.
//!
//! The submit path only writes in the admitted environment (#344: local
//! Linux ext4). Every write assertion therefore runs behind the same
//! admission inspection the CLI itself performs; on any other environment
//! the tests assert the fail-closed refusal instead, so the suite stays
//! honest on tmpfs/macOS/Windows. Leftover operations for the recovery
//! tests are produced with the D library's own fault injection; the
//! recovery itself always goes through the real CLI. No real saves, books
//! or secrets.

