#[test]
fn derivation_applies_the_constitution_retroactive_rule() {
    let fixture = Fixture::new(10, "5e-srd");
    fixture.card(
        FIGHTER_2014_BLOCK,
        FIGHTER_2014_RECORDS,
        false,
        "2014",
        "class: fighter",
        "",
        None,
    );
    fixture.chargen("Synthetic Hero", "fighter", &["athletics"]);
    let (ok, report) = fixture.derive(&[
        "--select-opportunity",
        "ability_score_improvement_or_optional_feat",
        "--select-abilities",
        "con+2",
    ]);
    assert!(ok, "derive failed: {}", report);
    // con 14→16: the proficient con save moves 4→5, and the maximum rises by
    // the new level's gain (d10 average 6 + new con +3 = 9) plus the
    // retroactive +1 for each of the 3 attained levels.
    assert_eq!(
        auto_values(&report, "combat.abilities.con"),
        (json!(14), json!(16))
    );
    assert_eq!(
        auto_values(&report, "combat.saves.con"),
        (json!(4), json!(5))
    );
    assert_eq!(auto_values(&report, "combat.hp"), (json!(28), json!(40)));
    assert!(entry(&report, "combat.hp")["reason"]
        .as_str()
        .unwrap()
        .contains("追溯"));
    // str stays put and its proven dependent values keep.
    assert_eq!(disposition(&report, "combat.saves.str"), "keep");
    assert_eq!(disposition(&report, "combat.skills.athletics"), "keep");
}

