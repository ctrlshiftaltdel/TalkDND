#[test]
fn mixed_or_incomplete_hp_history_stays_unproven() {
    let selection = [
        "--select-opportunity",
        "ability_score_improvement_or_optional_feat",
        "--select-abilities",
        "str+2",
    ];
    let fighter = |fixture: &Fixture, lines: &[&str]| {
        fixture.card(
            FIGHTER_2014_BLOCK,
            &records_with(lines),
            false,
            "2014",
            "class: fighter",
            "",
            None,
        )
    };
    // (a) Mixed history: level 2 was rolled, level 3 average.
    let fixture = Fixture::new(10, "5e-srd");
    fighter(
        &fixture,
        &[
            "- 2026-01-01：升到 2 级；HP +9（d10 1d10+2 = 9 [7,2] + 2，体质 +2）→ 19；熟练 +2",
            "- 2026-01-02：升到 3 级；HP +8（d10 average 8，体质 +2）→ 27；熟练 +2",
        ],
    );
    let (ok, report) = fixture.derive(&selection);
    assert!(ok, "derive failed: {}", report);
    assert_eq!(disposition(&report, "combat.hp"), "dm_review");
    assert!(entry(&report, "combat.hp")["reason"]
        .as_str()
        .unwrap()
        .contains("不是平均模式"));

    // (b) Missing history: only the level-3 line survives.
    let fixture = Fixture::new(10, "5e-srd");
    fighter(
        &fixture,
        &["- 2026-01-02：升到 3 级；HP +8（d10 average 8，体质 +2）→ 28；熟练 +2"],
    );
    let (ok, report) = fixture.derive(&selection);
    assert!(ok, "derive failed: {}", report);
    assert_eq!(disposition(&report, "combat.hp"), "dm_review");
    assert!(entry(&report, "combat.hp")["reason"]
        .as_str()
        .unwrap()
        .contains("缺少 2 级"));

    // (c) Duplicate records for the same level.
    let fixture = Fixture::new(10, "5e-srd");
    fighter(
        &fixture,
        &[
            "- 2026-01-01：升到 2 级；HP +8（d10 average 8，体质 +2）→ 20；熟练 +2",
            "- 2026-01-02：升到 3 级；HP +8（d10 average 8，体质 +2）→ 28；熟练 +2",
            "- 2026-01-03：升到 3 级；HP +8（d10 average 8，体质 +2）→ 28；熟练 +2",
        ],
    );
    let (ok, report) = fixture.derive(&selection);
    assert!(ok, "derive failed: {}", report);
    assert_eq!(disposition(&report, "combat.hp"), "dm_review");
    assert!(entry(&report, "combat.hp")["reason"]
        .as_str()
        .unwrap()
        .contains("重复或矛盾"));

    // (d) Contradictory totals: the chain math breaks at level 3.
    let fixture = Fixture::new(10, "5e-srd");
    fighter(
        &fixture,
        &[
            "- 2026-01-01：升到 2 级；HP +8（d10 average 8，体质 +2）→ 20；熟练 +2",
            "- 2026-01-02：升到 3 级；HP +8（d10 average 8，体质 +2）→ 30；熟练 +2",
        ],
    );
    let (ok, report) = fixture.derive(&selection);
    assert!(ok, "derive failed: {}", report);
    assert_eq!(disposition(&report, "combat.hp"), "dm_review");
    assert!(entry(&report, "combat.hp")["reason"]
        .as_str()
        .unwrap()
        .contains("不一致"));

    // (e) The con recorded by the last level-up no longer matches the block:
    // the con was changed after the last program level-up, so the retroactive
    // calculation has no provable base.
    let fixture = Fixture::new(10, "5e-srd");
    let hand_con = FIGHTER_2014_BLOCK.replace("con: 14", "con: 16");
    fixture.card(
        &hand_con,
        FIGHTER_2014_RECORDS,
        false,
        "2014",
        "class: fighter",
        "",
        None,
    );
    let (ok, report) = fixture.derive(&selection);
    assert!(ok, "derive failed: {}", report);
    assert_eq!(disposition(&report, "combat.hp"), "dm_review");
    assert!(entry(&report, "combat.hp")["reason"]
        .as_str()
        .unwrap()
        .contains("体质被改动"));
}

