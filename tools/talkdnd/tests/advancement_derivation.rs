#[test]
fn repeated_derivation_is_byte_identical() {
    let fixture = Fixture::new(10, "5e-srd");
    fixture.card(
        FIGHTER_2014_BLOCK,
        FIGHTER_2014_RECORDS,
        false,
        "2014",
        "class: fighter",
        "",
        None,
    );
    let extra = [
        "--select-opportunity",
        "ability_score_improvement_or_optional_feat",
        "--select-abilities",
        "str+2",
    ];
    let first = fixture.derive(&extra);
    let second = fixture.derive(&extra);
    assert!(first.0 && second.0);
    // The candidate is a pure function of the same fixture state: entries
    // carry absolute before/after values, so nothing accumulates across
    // runs. Applying the candidate and re-verifying it afterwards is #333's
    // commit gate and is not implemented in this task.
    assert_eq!(first.1, second.1);
    let entries = first.1["derived"]["entries"].as_array().unwrap();
    assert!(entries.iter().all(|row| {
        row["disposition"] != "auto"
            || (row["before"].is_i64() && row["after"].is_i64() && row["target"].is_string())
    }));
}

