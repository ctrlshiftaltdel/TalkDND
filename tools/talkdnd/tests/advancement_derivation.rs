struct Fixture {
    root: PathBuf,
    save: PathBuf,
}

impl Fixture {
    fn new(schema: u32, ruleset: &str) -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let root = loop {
            let path = std::env::temp_dir().join(format!(
                "talkdnd-growth-derive-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            match fs::create_dir(&path) {
                Ok(()) => break path,
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(error) => panic!("could not create derivation fixture: {error}"),
            }
        };
        let save = root.join("Saves/2030-01-02-01");
        let fixture = Self { root, save };
        write(&fixture.root, "AGENTS.md", b"synthetic play root");
        write(
            &fixture.save,
            "save-meta.yaml",
            format!("schema: {schema}\n").as_bytes(),
        );
        write(
            &fixture.save,
            "combat/campaign.yaml",
            format!("name: Fixture\nruleset: \"{ruleset}\"\nstate_dir: .\nparty: [hero]\n")
                .as_bytes(),
        );
        write(&fixture.save, "combat/party-state.yaml", b"members: {}\n");
        write(&fixture.save, "world-time.yaml", b"{}\n");
        write(&fixture.save, "Sessions/2030-01-02.md", b"synthetic log\n");
        fixture
    }

    /// Writes the save's existing chargen state (`chargen.json`): the record
    /// of the skills the player actually chose, attributed by name.
    fn chargen(&self, name: &str, class: &str, skills: &[&str]) {
        let skills = skills
            .iter()
            .map(|skill| format!("\"{skill}\""))
            .collect::<Vec<_>>()
            .join(", ");
        write(
            &self.save,
            "chargen.json",
            format!(
                "{{
  \"name\": \"{name}\",
  \"class\": \"{class}\",
  \"skills\": [{skills}]
}}
"
            )
            .as_bytes(),
        );
    }

    /// Writes the Markdown card (combat block + level records) and, unless
    /// `legacy`, the structured sheet mirroring it. `info` is the sheet's
    /// `info` mapping content; `sheet_extra` carries the optional `spells`
    /// block; `block_override` splices hand edits into both carriers.
    fn card(
        &self,
        block: &str,
        records: &str,
        legacy: bool,
        ruleset: &str,
        info: &str,
        sheet_extra: &str,
        block_override: Option<&(&str, &str)>,
    ) {
        let block = match block_override {
            Some((from, to)) => block.replace(from, to),
            None => block.to_owned(),
        };
        write(
            &self.save,
            "Characters/hero.md",
            format!("# Synthetic Hero\n\n```combat yaml\n{block}```\n\n{records}\n").as_bytes(),
        );
        if legacy {
            return;
        }
        let indented: String = block
            .lines()
            .map(|line| {
                if line.is_empty() {
                    String::from("\n")
                } else {
                    format!("  {line}\n")
                }
            })
            .collect();
        write(
            &self.save,
            "sheets/hero.yaml",
            format!(
                "version: 1\nid: hero\nname: Synthetic Hero\nfile: Characters/hero.md\nruleset: \"{ruleset}\"\ncontroller: player\ninfo: {{{info}}}\nfeats: []\n{sheet_extra}combat:\n{indented}",
            )
            .as_bytes(),
        );
    }

    fn pack(&self, edition: &str, dist: Distribution, id: &str, feat: DomainEntity) {
        let pack = ContentPack::new(
            PackMeta {
                id: id.into(),
                name: None,
                edition: edition.into(),
                source: Some("synthetic".into()),
                license: Some("test".into()),
                distribution: dist,
                schema_version: combat_sim::content::pack::SCHEMA_VERSION,
                content_hash: None,
                created_at: None,
                description: None,
            },
            ContentFile {
                feats: Some(vec![feat]),
                ..Default::default()
            },
        )
        .unwrap();
        let path = if dist == Distribution::Full {
            format!("Rules/packs/{id}.pack.json")
        } else {
            format!("Rules/combat/{edition}/srd/{id}.pack.json")
        };
        write(&self.root, &path, &serde_json::to_vec(&pack).unwrap());
    }

    fn unlock_book(&self, edition: &str) {
        write(
            &self.root,
            ".talkdnd/books.yaml",
            format!(
                "books:\n- edition: \"{edition}\"\n  book: phb\n  status: identified\n  source: Rules/{edition}/synthetic/index\n  method: content\n  evidence: synthetic\n  stamp: fixture\n"
            )
            .as_bytes(),
        );
    }

    fn command(&self, args: &[&str]) -> Output {
        let before = snapshot(&self.root);
        let output = Command::new(env!("CARGO_BIN_EXE_talkdnd"))
            .arg("--root")
            .arg(&self.root)
            .args(args)
            .output()
            .unwrap();
        assert_eq!(
            before,
            snapshot(&self.root),
            "the CLI changed the fixture for {args:?}"
        );
        output
    }

    /// Runs one derivation and parses the structured report from stdout; the
    /// report is printed before the exit code, so rejections parse too.
    fn derive(&self, extra: &[&str]) -> (bool, Value) {
        let mut args = vec![
            "advancement",
            "identity-preview",
            "--level-up",
            "hero",
            "--json",
            "--derive",
        ];
        args.extend_from_slice(extra);
        let output = self.command(&args);
        let report: Value = serde_json::from_slice(&output.stdout).unwrap();
        (output.status.success(), report)
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        // The fixture creates this directory atomically and owns it.
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn write(root: &Path, relative: &str, data: &[u8]) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, data).unwrap();
}

fn snapshot(root: &Path) -> BTreeMap<PathBuf, Option<Vec<u8>>> {
    fn visit(root: &Path, path: &Path, tree: &mut BTreeMap<PathBuf, Option<Vec<u8>>>) {
        for entry in fs::read_dir(path).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            let directory = entry.file_type().unwrap().is_dir();
            let contents = (!directory).then(|| fs::read(&path).unwrap());
            tree.insert(path.strip_prefix(root).unwrap().to_path_buf(), contents);
            if directory {
                visit(root, &path, tree);
            }
        }
    }
    let mut tree = BTreeMap::new();
    visit(root, root, &mut tree);
    tree
}

fn feat(id: &str, minimum: u32) -> DomainEntity {
    DomainEntity {
        id: id.into(),
        name: Some(format!("Fixture {id}")),
        text: Some("never print synthetic rule body".into()),
        manual: Some("never print synthetic hidden effect".into()),
        data: Some(json!({ "prerequisites": { "minimum_level": minimum } })),
        ..Default::default()
    }
}

fn entry<'a>(report: &'a Value, id: &str) -> &'a Value {
    report["derived"]["entries"]
        .as_array()
        .unwrap()
        .iter()
        .find(|row| row["id"] == id)
        .unwrap_or_else(|| panic!("missing derived entry {id}"))
}

fn disposition(report: &Value, id: &str) -> String {
    entry(report, id)["disposition"]
        .as_str()
        .unwrap()
        .to_owned()
}

fn has_entry(report: &Value, id: &str) -> bool {
    report["derived"]["entries"]
        .as_array()
        .unwrap()
        .iter()
        .any(|row| row["id"] == id)
}

fn auto_values(report: &Value, id: &str) -> (Value, Value) {
    let row = entry(report, id);
    assert_eq!(row["disposition"], "auto", "entry {id} must be auto");
    (
        row["before"].as_i64().unwrap().into(),
        row["after"].as_i64().unwrap().into(),
    )
}

/// Hand-written history lines for the HP negatives.
fn records_with(lines: &[&str]) -> String {
    format!("## 升级记录\n\n{}\n", lines.join("\n"))
}

