#[test]
fn derivation_auto_updates_reliable_values_on_2014_srd() {
    let fixture = Fixture::new(10, "5e-srd");
    fixture.card(
        FIGHTER_2014_BLOCK,
        FIGHTER_2014_RECORDS,
        false,
        "2014",
        "class: fighter",
        "",
        None,
    );
    // The chargen state records the skill actually chosen at creation.
    fixture.chargen("Synthetic Hero", "fighter", &["athletics"]);
    let (ok, report) = fixture.derive(&[
        "--select-opportunity",
        "ability_score_improvement_or_optional_feat",
        "--select-abilities",
        "str+2",
    ]);
    assert!(ok, "derive failed: {}", report);
    let derived = &report["derived"];
    assert_eq!(derived["application"], "not_applied_read_only_candidate");
    assert_eq!(derived["encounter_gate"], "clear_at_read");

    // Proven-source derivations, each proposed exactly once with absolute
    // values.
    assert_eq!(auto_values(&report, "combat.level"), (json!(3), json!(4)));
    assert_eq!(
        auto_values(&report, "combat.abilities.str"),
        (json!(16), json!(18))
    );
    assert_eq!(auto_values(&report, "combat.hp"), (json!(28), json!(36)));
    assert_eq!(
        auto_values(&report, "combat.saves.str"),
        (json!(5), json!(6))
    );
    assert_eq!(
        auto_values(&report, "combat.skills.athletics"),
        (json!(5), json!(6))
    );
    assert_eq!(
        auto_values(&report, "combat.attacks.longsword.to_hit"),
        (json!(5), json!(6))
    );
    assert_eq!(
        auto_values(&report, "combat.attacks.unarmed.to_hit"),
        (json!(5), json!(6))
    );
    assert_eq!(
        auto_values(&report, "combat.resources.hit-dice.max"),
        (json!(3), json!(4))
    );

    // Unchanged-but-proven values are keeps, not rewrites.
    assert_eq!(disposition(&report, "combat.prof"), "keep");
    assert_eq!(disposition(&report, "combat.saves.con"), "keep");
    // Class-choosable skills without a matching chargen record prove
    // nothing, even though their values equal mod + proficiency.
    assert_eq!(
        disposition(&report, "combat.skills.perception"),
        "dm_review"
    );
    assert_eq!(disposition(&report, "combat.skills.history"), "dm_review");
    assert_eq!(
        disposition(&report, "combat.skills.intimidation"),
        "dm_review"
    );
    assert_eq!(disposition(&report, "combat.abilities.other"), "keep");

    // Numeric collision without a provable source: sleight-of-hand is not in
    // the fighter choosable list, and 3 happens to equal dex mod + proficiency.
    assert_eq!(
        disposition(&report, "combat.skills.sleight-of-hand"),
        "dm_review"
    );
    assert!(entry(&report, "combat.skills.sleight-of-hand")["reason"]
        .as_str()
        .unwrap()
        .contains("来源无法证实"));

    // Unknown provenance and candidate boundaries.
    assert_eq!(
        disposition(&report, "combat.resources.second-flask.max"),
        "dm_review"
    );
    assert_eq!(disposition(&report, "combat.resources.current"), "keep");
    assert_eq!(disposition(&report, "spell_lists"), "keep");
    assert_eq!(disposition(&report, "combat_refs"), "keep");
    assert_eq!(disposition(&report, "resource_currents"), "keep");
    assert_eq!(disposition(&report, "encounter_state"), "keep");
}

