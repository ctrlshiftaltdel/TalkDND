#[test]
fn unrecognized_feats_mark_manual_only_after_the_three_rules_pass() {
    // Declared authorized source + structured sheet: opportunity, authorization
    // and duplicates all pass, so the marking applies.
    let fixture = Fixture::new(10, "5e-srd");
    fixture.pack(
        "2014",
        Distribution::Srd,
        "srd-5.1-feats",
        feat("brave-strike", "general", 4),
    );
    fixture.sheet("2014", 3, &[]);
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "book-only-feat",
        "--select-source",
        "srd-5.1-feats",
        "--dm-confirm",
        "玩家书籍核对通过",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "confirmed_unknown");
    assert_eq!(report["selection"]["candidate"]["recognized"], false);
    assert_eq!(
        report["selection"]["unrecognized_marking"],
        "unverified_effects_manual"
    );
    assert_eq!(row_status(&report, "prerequisites_verifiable"), "unknown");

    // Without a declared source the attribution cannot be proven inside the
    // authorized scope: the authorization stays unknown and rejects, and the
    // DM basis cannot upgrade it into a continuation.
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "book-only-feat",
        "--dm-confirm",
        "来源由 DM 核对",
    ]);
    assert!(!ok);
    assert_eq!(report["selection"]["decision"], "rejected");
    assert!(report["selection"]["unrecognized_marking"].is_null());
    assert_eq!(row_status(&report, "candidate_authorized"), "unknown");

    // A declared wrong source (the other edition's catalog) rejects.
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "book-only-feat",
        "--select-source",
        "srd-5.2.1-feats",
    ]);
    assert!(!ok);
    assert_eq!(row_status(&report, "candidate_authorized"), "not_met");

    // An unknown source pack keeps the authorization unprovable and rejects,
    // no matter the DM basis; the manual marking never applies.
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "book-only-feat",
        "--select-source",
        "mystery-pack",
        "--dm-confirm",
        "来源待查",
    ]);
    assert!(!ok);
    assert_eq!(report["selection"]["decision"], "rejected");
    assert!(report["selection"]["unrecognized_marking"].is_null());
    assert_eq!(row_status(&report, "candidate_authorized"), "unknown");

    // Aliases, display names and malformed specs are input errors.
    for args in [
        vec![
            "--select-opportunity",
            ASI_2014,
            "--select-feat",
            "Brave-Strike",
        ],
        vec![
            "--select-opportunity",
            ASI_2014,
            "--select-feat",
            " brave-strike",
        ],
        vec![
            "--select-opportunity",
            ASI_2014,
            "--select-abilities",
            "strength+2",
        ],
        vec![
            "--select-opportunity",
            ASI_2014,
            "--select-abilities",
            "str+2;",
        ],
        vec![
            "--select-opportunity",
            ASI_2014,
            "--select-abilities",
            "str+3",
        ],
        vec![
            "--select-opportunity",
            ASI_2014,
            "--select-abilities",
            "str+1,str+1",
        ],
        vec!["--select-opportunity", ASI_2014],
    ] {
        let output = fixture.command(
            &["advancement", "identity-preview", "--level-up", "hero"]
                .into_iter()
                .chain(args.iter().copied())
                .collect::<Vec<_>>(),
        );
        assert!(!output.status.success(), "args {args:?} must be rejected");
    }
}

