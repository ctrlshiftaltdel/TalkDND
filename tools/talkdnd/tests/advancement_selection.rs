//! Synthetic saves exercising the read-only selection validation through the
//! real CLI. Every invocation asserts a whole-tree byte-identical fixture:
//! success, input errors and rejections must all write nothing.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

use combat_sim::content::schema::{ContentFile, DomainEntity};
use combat_sim::content::{ContentPack, Distribution, PackMeta};
use serde_json::{json, Value};

const ASI_2014: &str = "ability_score_improvement_or_optional_feat";
const ASI_2024: &str = "ability_score_improvement_feat_or_other_qualified_feat";
const EPIC_BOON: &str = "epic_boon_or_other_qualified_feat";

struct Fixture {
    root: PathBuf,
    save: PathBuf,
}

impl Fixture {
    fn new(schema: u32, ruleset: &str) -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let root = loop {
            let path = std::env::temp_dir().join(format!(
                "talkdnd-growth-select-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            match fs::create_dir(&path) {
                Ok(()) => break path,
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
                Err(error) => panic!("could not create selection fixture: {error}"),
            }
        };
        let save = root.join("Saves/2030-01-02-01");
        let fixture = Self { root, save };
        write(&fixture.root, "AGENTS.md", b"synthetic play root");
        write(
            &fixture.save,
            "save-meta.yaml",
            format!("schema: {schema}\n").as_bytes(),
        );
        write(
            &fixture.save,
            "combat/campaign.yaml",
            format!("name: Fixture\nruleset: \"{ruleset}\"\nstate_dir: .\nparty: [hero]\n")
                .as_bytes(),
        );
        fixture.card(3, "");
        write(&fixture.save, "Sessions/2030-01-02.md", b"synthetic log\n");
        fixture
    }

    fn card(&self, level: i32, after: &str) {
        self.card_abilities(level, "{str: 17, dex: 20, con: 12}", after);
    }

    fn card_abilities(&self, level: i32, abilities: &str, after: &str) {
        write(
            &self.save,
            "Characters/hero.md",
            format!(
                "# Synthetic Hero\n\n```combat yaml\nid: hero\nname: Synthetic Hero\nlevel: {level}\nabilities: {abilities}\nnotes: fighter 3. Generated by talkdnd from SRD/local data\n```\n{after}"
            )
            .as_bytes(),
        );
    }

    /// Structured sheet mirroring the card; `feats` is the recorded feat list.
    fn sheet(&self, ruleset: &str, level: i32, feats: &[&str]) {
        let feats = if feats.is_empty() {
            "[]".to_owned()
        } else {
            format!("[{}]", feats.join(", "))
        };
        write(
            &self.save,
            "sheets/hero.yaml",
            format!(
                "version: 1\nid: hero\nname: Synthetic Hero\nfile: Characters/hero.md\nruleset: \"{ruleset}\"\ncontroller: player\ninfo: {{class: fighter}}\nfeats: {feats}\ncombat: {{level: {level}, abilities: {{str: 17, dex: 20, con: 12}}}}\n"
            )
            .as_bytes(),
        );
    }

    /// Structured sheet with custom ability scores (mirrored on the card).
    fn sheet_abilities(&self, ruleset: &str, level: i32, abilities: &str) {
        write(
            &self.save,
            "sheets/hero.yaml",
            format!(
                "version: 1\nid: hero\nname: Synthetic Hero\nfile: Characters/hero.md\nruleset: \"{ruleset}\"\ncontroller: player\ninfo: {{class: fighter}}\ncombat: {{level: {level}, abilities: {abilities}}}\n"
            )
            .as_bytes(),
        );
    }

    fn pack(&self, edition: &str, dist: Distribution, id: &str, feat: DomainEntity) {
        self.pack_many(edition, dist, id, &[feat]);
    }

    /// One pack file per id: the preview reads exactly one SRD feats pack per
    /// edition, so a catalog with several feats packs them together.
    fn pack_many(&self, edition: &str, dist: Distribution, id: &str, feats: &[DomainEntity]) {
        let pack = ContentPack::new(
            PackMeta {
                id: id.into(),
                name: None,
                edition: edition.into(),
                source: Some("synthetic".into()),
                license: Some("test".into()),
                distribution: dist,
                schema_version: combat_sim::content::pack::SCHEMA_VERSION,
                content_hash: None,
                created_at: None,
                description: None,
            },
            ContentFile {
                feats: Some(feats.to_vec()),
                ..Default::default()
            },
        )
        .unwrap();
        let path = if dist == Distribution::Full {
            format!("Rules/packs/{id}.pack.json")
        } else {
            format!("Rules/combat/{edition}/srd/{id}.pack.json")
        };
        write(&self.root, &path, &serde_json::to_vec(&pack).unwrap());
    }

    fn unlock_book(&self, edition: &str) {
        write(
            &self.root,
            ".talkdnd/books.yaml",
            format!(
                "books:\n- edition: \"{edition}\"\n  book: phb\n  status: identified\n  source: Rules/{edition}/synthetic/index\n  method: content\n  evidence: synthetic\n  stamp: fixture\n"
            )
            .as_bytes(),
        );
    }

    fn command(&self, args: &[&str]) -> Output {
        let before = snapshot(&self.root);
        let output = Command::new(env!("CARGO_BIN_EXE_talkdnd"))
            .arg("--root")
            .arg(&self.root)
            .args(args)
            .output()
            .unwrap();
        assert_eq!(
            before,
            snapshot(&self.root),
            "the CLI changed the fixture for {args:?}"
        );
        output
    }

    /// Runs one selection and parses the structured report from stdout; the
    /// report is printed before the exit code, so rejections parse too.
    fn select(&self, extra: &[&str]) -> (bool, Value) {
        let mut args = vec![
            "advancement",
            "identity-preview",
            "--level-up",
            "hero",
            "--json",
        ];
        args.extend_from_slice(extra);
        let output = self.command(&args);
        let report: Value = serde_json::from_slice(&output.stdout).unwrap();
        (output.status.success(), report)
    }

    fn condition<'a>(report: &'a Value, id: &str) -> &'a Value {
        report["selection"]["conditions"]
            .as_array()
            .unwrap()
            .iter()
            .find(|row| row["id"] == id)
            .unwrap_or_else(|| panic!("missing condition {id}"))
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        // The fixture creates this directory atomically and owns it.
        let _ = fs::remove_dir_all(&self.root);
    }
}

fn write(root: &Path, relative: &str, data: &[u8]) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, data).unwrap();
}

fn snapshot(root: &Path) -> BTreeMap<PathBuf, Option<Vec<u8>>> {
    fn visit(root: &Path, path: &Path, tree: &mut BTreeMap<PathBuf, Option<Vec<u8>>>) {
        for entry in fs::read_dir(path).unwrap() {
            let entry = entry.unwrap();
            let path = entry.path();
            let directory = entry.file_type().unwrap().is_dir();
            let contents = (!directory).then(|| fs::read(&path).unwrap());
            tree.insert(path.strip_prefix(root).unwrap().to_path_buf(), contents);
            if directory {
                visit(root, &path, tree);
            }
        }
    }
    let mut tree = BTreeMap::new();
    visit(root, root, &mut tree);
    tree
}

fn feat(id: &str, category: &str, minimum: u32) -> DomainEntity {
    feat_with(
        id,
        category,
        json!({ "prerequisites": { "minimum_level": minimum } }),
    )
}

fn feat_with(id: &str, category: &str, mut data: Value) -> DomainEntity {
    // 2024-style packs carry `type`; 2014-style entries pass "" and keep the
    // bare prerequisite shape.
    if !category.is_empty() {
        if let Some(obj) = data.as_object_mut() {
            obj.insert("type".to_owned(), Value::String(category.to_owned()));
        }
    }
    DomainEntity {
        id: id.into(),
        name: Some(format!("Fixture {id}")),
        text: Some("never print synthetic rule body".into()),
        manual: Some("never print synthetic hidden effect".into()),
        data: Some(data),
        ..Default::default()
    }
}

/// A pack entry whose description was not retained: the duplicate rule must
/// treat its extraction completeness as unknown.
fn feat_without_text(id: &str, category: &str, data: Value) -> DomainEntity {
    let mut feat = feat_with(id, category, data);
    feat.text = None;
    feat
}

fn row_status<'a>(report: &'a Value, id: &str) -> &'a str {
    Fixture::condition(report, id)["status"].as_str().unwrap()
}

