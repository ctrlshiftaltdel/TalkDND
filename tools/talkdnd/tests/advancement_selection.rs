#[test]
fn explicit_selections_verify_with_condition_sources_on_both_editions() {
    // 2014: feat candidate, ability prerequisite from the 2014 array shape,
    // and a fighting-style feature_named prerequisite.
    let fixture = Fixture::new(10, "5e-srd");
    fixture.pack_many(
        "2014",
        Distribution::Srd,
        "srd-5.1-feats",
        &[
            feat("brave-strike", "general", 4),
            feat_with(
                "tough-grip",
                "",
                json!({ "prerequisites": [
                    {"ability_score": {"index": "str"}, "minimum_score": 13},
                ]}),
            ),
            feat_with(
                "archery-style",
                "fighting-style",
                json!({ "prerequisites": { "feature_named": "Fighting Style" } }),
            ),
        ],
    );
    fixture.sheet("2014", 3, &[]);
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "brave-strike",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "verified");
    assert_eq!(report["selection"]["not_program_verified"], false);
    assert_eq!(
        report["selection"]["application"],
        "not_applied_read_only_validation"
    );
    assert!(report["selection"]["unrecognized_marking"].is_null());
    let matches = Fixture::condition(&report, "opportunity_matches");
    assert_eq!(matches["status"], "met");
    assert_eq!(matches["edition"], "2014");
    assert_eq!(matches["source"], "SRD 5.1 class progression");
    let authorized = Fixture::condition(&report, "candidate_authorized");
    assert_eq!(authorized["status"], "met");
    assert_eq!(authorized["source"], "srd-5.1-feats");
    assert_eq!(row_status(&report, "prerequisite_minimum_level"), "met");
    assert_eq!(row_status(&report, "known_duplicate"), "met");
    assert_eq!(
        report["selection"]["candidate"]["name"],
        "Fixture brave-strike"
    );

    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "tough-grip",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "verified");
    let prereq = Fixture::condition(&report, "prerequisite_ability_str");
    assert_eq!(prereq["status"], "met");
    assert_eq!(prereq["edition"], "2014");
    assert!(prereq["detail"].as_str().unwrap().contains("17"));

    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-feat",
        "archery-style",
    ]);
    assert!(ok);
    assert_eq!(row_status(&report, "prerequisite_feature_named"), "met");

    // Ability increase candidate: str 17 -> 19 stays within the 20 cap.
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2014,
        "--select-abilities",
        "str+2",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "verified");
    assert_eq!(
        row_status(&report, "opportunity_grants_ability_increase"),
        "met"
    );
    assert_eq!(row_status(&report, "increase_total_matches_grant"), "met");
    assert_eq!(row_status(&report, "str_increase_within_cap"), "met");
    let cap = Fixture::condition(&report, "str_increase_within_cap");
    assert_eq!(
        cap["source"],
        "SRD 5.1 class progression (Ability Score Improvement)"
    );
    assert_eq!(
        report["selection"]["candidate"]["increases"][0]["score_after"],
        19
    );

    // 2024: the same shape against its own catalog and edition labels.
    let fixture = Fixture::new(9, "5.5e-srd");
    fixture.pack(
        "2024",
        Distribution::Srd,
        "srd-5.2.1-feats",
        feat("brave-strike-24", "general", 4),
    );
    fixture.sheet("2024", 3, &[]);
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2024,
        "--select-feat",
        "brave-strike-24",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "verified");
    assert_eq!(
        Fixture::condition(&report, "opportunity_matches")["edition"],
        "2024"
    );
    assert_eq!(
        Fixture::condition(&report, "candidate_authorized")["source"],
        "srd-5.2.1-feats"
    );

    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2024,
        "--select-abilities",
        "con+1,str+1",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "verified");
    assert_eq!(row_status(&report, "str_increase_within_cap"), "met");
    assert_eq!(row_status(&report, "con_increase_within_cap"), "met");
}

#[test]
fn full_campaign_authorizes_only_unlocked_same_edition_packs() {
    let fixture = Fixture::new(10, "5.5e-full");
    fixture.pack(
        "2024",
        Distribution::Srd,
        "srd-5.2.1-feats",
        feat("srd-2024-strike", "general", 4),
    );
    fixture.pack(
        "2024",
        Distribution::Full,
        "full-2024-phb",
        feat("full-2024-strike", "general", 4),
    );
    fixture.pack(
        "2024",
        Distribution::Full,
        "full-2024-dmg",
        feat("full-locked-strike", "general", 4),
    );
    fixture.unlock_book("2024");
    fixture.sheet("2024", 3, &[]);
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2024,
        "--select-feat",
        "full-2024-strike",
    ]);
    assert!(ok);
    assert_eq!(report["selection"]["decision"], "verified");
    assert_eq!(
        Fixture::condition(&report, "candidate_authorized")["source"],
        "full-2024-phb"
    );

    // A locked same-edition FULL source is categorically unauthorized when the
    // player declares it; the pack entity is never read for the verdict.
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2024,
        "--select-feat",
        "full-locked-strike",
        "--select-source",
        "full-2024-dmg",
    ]);
    assert!(!ok);
    assert_eq!(report["selection"]["decision"], "rejected");
    assert_eq!(
        Fixture::condition(&report, "candidate_authorized")["status"],
        "not_met"
    );

    // Without a declaration the attribution cannot be proven inside the
    // authorized scope: rejected, and a DM basis cannot upgrade it.
    let (ok, report) = fixture.select(&[
        "--select-opportunity",
        ASI_2024,
        "--select-feat",
        "full-locked-strike",
        "--dm-confirm",
        "reviewed",
    ]);
    assert!(!ok);
    assert_eq!(report["selection"]["decision"], "rejected");
    assert_eq!(
        Fixture::condition(&report, "candidate_authorized")["status"],
        "unknown"
    );
    assert!(report.to_string().contains("DM 确认不能补足授权"));
}

